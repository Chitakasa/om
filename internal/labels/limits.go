package labels

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/Chitakasa/om/internal/py"
	"github.com/Chitakasa/om/internal/state"
)

// Resource limits from labels, as a compose override passed at start:
//
//	om.mem=256m   memory limit (k, m or g)
//	om.pids=200   most processes and threads
//	om.cpus=0.5   CPU cores
//
// A label that does not parse is reported and ignored (the service runs without that limit).
// Port of lib/gitops/limits.py. Go's `$` matches only at the end of the text, like Python's `\Z`.
var (
	memRE  = regexp.MustCompile(`(?i)^([1-9][0-9]{0,8})([kmg])b?$`)
	pidsRE = regexp.MustCompile(`^[1-9][0-9]{0,5}$`)
	cpusRE = regexp.MustCompile(`^(?:[0-9]+\.?[0-9]*|\.[0-9]+)$`)
)

// Limit is one compose key with its already-rendered YAML/JSON value.
type Limit struct {
	Key   string
	Value string
}

// ParseLimits returns the compose keys (sorted by key) and the problems for one service's om.mem, om.pids and
// om.cpus labels.
func ParseLimits(lbl map[string]any) (limits []Limit, problems []string) {
	if raw := py.Strip(py.Str(orEmpty(lbl, "om.mem"))); raw != "" {
		if m := memRE.FindStringSubmatch(raw); m != nil {
			limits = append(limits, Limit{"mem_limit", py.JSONString(m[1] + strings.ToLower(m[2]))})
		} else {
			problems = append(problems, fmt.Sprintf("om.mem=%s (use a number with k, m or g, e.g. 256m)", raw))
		}
	}
	if raw := py.Strip(py.Str(orEmpty(lbl, "om.pids"))); raw != "" {
		if pidsRE.MatchString(raw) {
			limits = append(limits, Limit{"pids_limit", raw})
		} else {
			problems = append(problems, fmt.Sprintf("om.pids=%s (use a whole number, e.g. 200)", raw))
		}
	}
	if raw := py.Strip(py.Str(orEmpty(lbl, "om.cpus"))); raw != "" {
		f, err := strconv.ParseFloat(raw, 64)
		if cpusRE.MatchString(raw) && err == nil && f >= 0.01 && f <= 256 {
			limits = append(limits, Limit{"cpus", py.FloatRepr(f)})
		} else {
			problems = append(problems, fmt.Sprintf("om.cpus=%s (use cores between 0.01 and 256, e.g. 0.5)", raw))
		}
	}
	sort.Slice(limits, func(i, j int) bool { return limits[i].Key < limits[j].Key })
	return limits, problems
}

// orEmpty is labels.get(key, ""): a missing label is "", an explicit null is str(None).
func orEmpty(m map[string]any, k string) any {
	if v, ok := m[k]; ok {
		return v
	}
	return ""
}

// OverridePath is where the override of one compose folder lives.
func OverridePath(d state.Dirs, ws, projectDir string) string {
	sum := sha256.Sum256([]byte(projectDir))
	return filepath.Join(d.State, "limits", "overrides", ws+"-"+hex.EncodeToString(sum[:])[:12]+".yml")
}

// WriteOverride writes the compose override for the services of one compose file (cfg is its `compose config`
// as JSON) and returns its path, or "" when no service has a limit (a stale file is removed).
func WriteOverride(d state.Dirs, ws, projectDir string, cfg map[string]any) (path string, problems []string, err error) {
	wanted := map[string][]Limit{}
	services, _ := cfg["services"].(map[string]any)
	names := make([]string, 0, len(services))
	for n := range services {
		names = append(names, n)
	}
	sort.Strings(names) // compose prints its config with sorted keys: problems follow that order
	for _, name := range names {
		svc, _ := services[name].(map[string]any)
		lim, bad := ParseLimits(Service(svc))
		for _, p := range bad {
			problems = append(problems, name+": "+p)
		}
		if len(lim) > 0 {
			wanted[name] = lim
		}
	}
	path = OverridePath(d, ws, projectDir)
	if len(wanted) == 0 {
		if e := os.Remove(path); e != nil && !os.IsNotExist(e) {
			return "", problems, e
		}
		return "", problems, nil
	}
	lines := []string{"# Generated by om from om.mem / om.pids / om.cpus labels. Do not edit.", "services:"}
	for _, n := range names {
		if len(wanted[n]) == 0 {
			continue
		}
		lines = append(lines, "  "+py.JSONString(n)+":")
		for _, l := range wanted[n] {
			lines = append(lines, "    "+l.Key+": "+l.Value)
		}
	}
	if err = os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", problems, err
	}
	return path, problems, os.WriteFile(path, []byte(strings.Join(lines, "\n")+"\n"), 0o644)
}
