func existingJavaOptions(svc map[string]any) string {
	switch env := svc["environment"].(type) {
	case map[string]any:
		if v, ok := env["JAVA_TOOL_OPTIONS"]; ok {
			return py.Str(v)
		}
		return ""
	case []any:
		existing := ""
		for _, e := range env {
			if s := py.Str(e); strings.HasPrefix(s, "JAVA_TOOL_OPTIONS=") {
				existing = strings.SplitN(s, "=", 2)[1]
			}
		}
		return existing
	}
	return ""
}

func serviceOverride(svc string, svcDict map[string]any, url, ip, netKey string, local []string) []string {
	lines := []string{"  " + py.JSONString(svc) + ":", "    environment:"}
	for _, k := range []string{"HTTP_PROXY", "HTTPS_PROXY", "http_proxy", "https_proxy"} {
		lines = append(lines, "      "+k+": "+py.JSONString(url))
	}
	for _, k := range []string{"NO_PROXY", "no_proxy"} {
		lines = append(lines, "      "+k+": "+py.JSONString(strings.Join(local, ",")))
	}
	if IsJVMService(svcDict) {
		merged := MergeJavaProxyOpts(existingJavaOptions(svcDict), Container, Port, strings.Join(local, "|"))
		lines = append(lines, "      JAVA_TOOL_OPTIONS: "+py.JSONString(merged))
	}
	return append(lines, "    networks:", "      "+netKey+":", "        ipv4_address: "+py.JSONString(ip))
}

// applyLearnLabel gives a service in learn or audit mode its record, with the TTL from its label (audit never
// expires).
func (e *Egress) applyLearnLabel(ws, svc string, svcDict map[string]any) error {
	lbl := labels.Service(svcDict)
	mode, ok := ParseLabel(lbl["om.egress"])
	if ok && (mode.Mode == Learn || mode.Mode == Audit) {
		ttl := 0
		if mode.Mode != Audit {
			ttl = ParseTTL(lbl["om.egress.learn_ttl"])
		}
		_, err := e.InitLearn(ws, svc, ttl, true)
		return err
	}
	return nil
}

// egressServices returns {service: proxy url} of the services that go through the proxy: those with a url in
// proxyURLs or, when proxyURLs is nil, those with an om.egress label (read from compose's dict form only).
func egressServices(services map[string]any, proxyURLs map[string]string) map[string]string {
	out := map[string]string{}
	for s, v := range services {
		if proxyURLs != nil {
			if u, ok := proxyURLs[s]; ok {
				out[s] = u
			}
			continue
		}
		svc, _ := v.(map[string]any)
		if l, ok := svc["labels"].(map[string]any); ok {
			if r, present := ParseLabel(l["om.egress"]); present && r.Truthy() {
				out[s] = ProxyURL()
			}
		}
	}
	return out
}

// WriteOverride writes the compose override giving each egress service its proxy settings and static IP. It
// returns the file's path, or "" when no service uses the proxy (a stale file is removed). proxyURLs and ips may
// be nil.
func (e *Egress) WriteOverride(ws, project string, cfg map[string]any, proxyURLs map[string]string, subnet string, ips map[string]string) (string, error) {
	services, _ := cfg["services"].(map[string]any)
	mine := egressServices(services, proxyURLs)
	sum := sha256.Sum256([]byte(project))
	path := filepath.Join(e.dir(), "overrides", ws+"-"+hex.EncodeToString(sum[:])[:12]+".yml")
	if len(mine) == 0 {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return "", err
		}
		return "", nil
	}
	assigned := ips
	if assigned == nil {
		assigned = e.loadIPs(ws)
	}
	set := map[string]bool{"localhost": true, "127.0.0.1": true, "::1": true}
	for name, v := range services {
		set[name] = true
		if s, _ := v.(map[string]any); py.Truthy(s["container_name"]) {
			set[py.Str(s["container_name"])] = true
		}
	}
	local := make([]string, 0, len(set))
	for k := range set {
		local = append(local, k)
	}
	sort.Strings(local)
	lines := []string{"# Generated by om — proxy settings for services with om.egress. Do not edit.", "services:"}
	names := make([]string, 0, len(mine))
	for s := range mine {
		names = append(names, s)
	}
	sort.Strings(names)
	for _, svc := range names {
		svcDict, _ := services[svc].(map[string]any)
		ip := assigned[svc]
		if ip == "" {
			var err error
			if ip, err = e.AllocateServiceIP(ws, svc, subnet); err != nil {
				return "", err
			}
		}
		if err := e.applyLearnLabel(ws, svc, svcDict); err != nil {
			return "", err
		}
		lines = append(lines, serviceOverride(svc, svcDict, mine[svc], ip, network.ServiceProjectNetworkKey(cfg, svc), local)...)
	}
	return path, e.writeFile(path, strings.Join(lines, "\n")+"\n", true)
}

// Squid native access log: time elapsed client code/status bytes method URL user hierarchy type
var logRE = regexp.MustCompile(`^([0-9]+\.[0-9]+)[` + wsClass + `]+[0-9]+[` + wsClass + `]+([^` + wsClass + `]+)[` + wsClass +
	`]+([^` + wsClass + `]+)[` + wsClass + `]+[0-9]+[` + wsClass + `]+([^` + wsClass + `]+)[` + wsClass + `]+([^` + wsClass +
	`]+)[` + wsClass + `]+([^` + wsClass + `]+)`)

// wsClass is Python's `\s` for str patterns (see routes.ws).
const wsClass = `\t\n\v\f\r \x{1c}-\x{1f}\x{85}\x{a0}\x{1680}\x{2000}-\x{200a}\x{2028}\x{2029}\x{202f}\x{205f}\x{3000}`

// DeniedHosts returns {"ws.svc": {host, …}} for requests the proxy refused (403). ips maps a client address to
// "ws.svc" (nil reads it from the state).
func (e *Egress) DeniedHosts(logText string, ips map[string]string) (map[string]map[string]bool, error) {
	return e.hosts(logText, func(code string) bool { return code == "TCP_DENIED/403" }, ips)
}

// UsedHosts returns {"ws.svc": {host, …}} for requests the proxy let through (learn and audit modes record
// these).
func (e *Egress) UsedHosts(logText string, ips map[string]string) (map[string]map[string]bool, error) {
	return e.hosts(logText, func(code string) bool { return !strings.HasPrefix(code, "TCP_DENIED") }, ips)
}

func (e *Egress) hosts(logText string, keep func(string) bool, ips map[string]string) (map[string]map[string]bool, error) {
	out := map[string]map[string]bool{}
	ipMap := ips
	if ipMap == nil {
		ipMap = e.AllServiceIPs()
	}
	for _, line := range py.SplitLines(logText) {
		m := logRE.FindStringSubmatch(py.Strip(line))
		if m == nil {
			continue
		}
		tsStr, clientIP, code, method, url, user := m[1], m[2], m[3], m[4], m[5], m[6]
		if !keep(code) {
			continue
		}
		key := user
		if user == "-" {
			key = ipMap[clientIP]
		}
		if key == "" {
			continue
		}
		var host string
		if method == "CONNECT" {
			host = strings.SplitN(url, ":", 2)[0]
		} else {
			parts := strings.Split(url, "://")
			h := parts[len(parts)-1] // split("://", 1)[-1]: everything after the first "://"
			if i := strings.Index(url, "://"); i >= 0 {
				h = url[i+3:]
			}
			host = strings.SplitN(strings.SplitN(h, "/", 2)[0], ":", 2)[0]
		}
		host = py.Strip(strings.ToLower(host))
		if host == "" || host == Container {
			// A client probing its own proxy (an HTTP/3 stack asks the proxy for MASQUE support at
			// /.well-known/masque/...) is not a host the service needs: never suggest allowing it.
			continue
		}
		if out[key] == nil {
			out[key] = map[string]bool{}
		}
		out[key][host] = true
		// Update learn tracking if request was allowed and the service is learning or auditing
		if !strings.HasPrefix(code, "TCP_DENIED") && strings.Contains(key, ".") {
			ws, svc, _ := strings.Cut(key, ".")
			if r, ok := e.loadRules(ws)[svc]; ok && (r.Mode == Learn || r.Mode == Audit) {
				ts, _ := strconv.ParseFloat(tsStr, 64)
				if err := e.RecordLearnedHost(ws, svc, host, ts); err != nil {
					return nil, err
				}
			}
		}
	}
	return out, nil
}
