func sortStrings(s []string) { sort.Strings(s) }

// RuntimeInputs are the facts runtime.env needs that other packages own.
type RuntimeInputs struct {
	EngineSocket string // "" falls back to /var/run/docker.sock
	EgressImage  string
	EdgeToken    string
	Hostname     string // this machine's name (mDNS .local name for LAN guests)
}

// KV is one runtime.env line; the file keeps this order.
type KV struct{ Key, Value string }

// RuntimeEnvPairs builds the values compose reads from runtime.env.
func RuntimeEnvPairs(d state.Dirs, r Resolved, in RuntimeInputs) []KV {
	vpn := append(append([]string{}, r.VPNIPs...), r.VPNNames...)
	var public []string
	if r.LANIP != "" {
		public = append(public, r.LANIP)
	}
	for _, ip := range r.VPNIPs {
		if ip != r.LANIP {
			public = append(public, ip)
		}
	}
	sock := in.EngineSocket
	if sock == "" {
		sock = "/var/run/docker.sock"
	}
	lan := r.LANIP
	if lan == "" {
		lan = state.Disabled("lan")
	}
	join := func(items []string, f func(string) string, sep, empty string) string {
		if len(items) == 0 {
			return empty
		}
		out := make([]string, len(items))
		for i, x := range items {
			out[i] = f(x)
		}
		return strings.Join(out, sep)
	}
	vh, vs := strconv.Itoa(state.VPNHTTPPort), strconv.Itoa(state.VPNHTTPSPort)
	var pubNames []string
	if r.LANIP != "" {
		first, _, _ := strings.Cut(in.Hostname, ".")
		pubNames = append(pubNames, r.LANIP, strings.ToLower(first)+".local")
	}
	pubNames = append(pubNames, vpn...)
	publicNames := strings.Join(pubNames, " ")
	if publicNames == "" {
		publicNames = state.Disabled("public-names")
	}
	vpnHosts := strings.Join(vpn, ",")
	if vpnHosts == "" {
		vpnHosts = state.Disabled("vpn")
	}
	return []KV{
		{"OM_ENGINE_SOCKET", sock},
		{"OM_WALLPAPERS_DIR", ComposePath(r.WallpapersDir)},
		{"OM_STATE_DIR", ComposePath(d.State)},
		{"LAN_IP", lan},
		// Several site addresses each (Caddy substitutes {$...} before parsing the Caddyfile).
		{"VPN_HTTP", join(vpn, func(h string) string { return "http://" + h + ":" + vh }, ", ", "http://"+state.Disabled("vpn-http")+":"+vh)},
		{"VPN_HTTPS", join(vpn, func(h string) string { return "https://" + h + ":" + vs }, ", ", "https://"+state.Disabled("vpn-https")+":"+vs)},
		{"PUBLIC_HTTPS", join(public, func(h string) string { return "https://" + h + ":8443" }, ", ", "https://"+state.Disabled("public")+":8443")},
		{"VPN_HOSTS", vpnHosts},
		// Host names a per-service port answers to (anything else is aborted: DNS rebinding).
		{"PRIVATE_NAMES", strings.Join(append([]string{"localhost", "127.0.0.1"}, vpn...), " ")},
		// <hostname>.local: the name the OS announces on the LAN (mDNS), as guests have always used it
		{"PUBLIC_NAMES", publicNames},
		{"OM_EDGE_TOKEN", in.EdgeToken},
		{"OM_EGRESS_IMAGE", in.EgressImage},
		{"OM_PRIVATE_PORT_BASE", strconv.Itoa(state.PrivatePortBase)},
		{"OM_PUBLIC_PORT_BASE", strconv.Itoa(state.PublicPortBase)},
	}
}

// RenderRuntimeEnv is the runtime.env text.
func RenderRuntimeEnv(d state.Dirs, pairs []KV) string {
	var b strings.Builder
	b.WriteString("# GENERATED by `om core start` — do not edit; edit " + d.UserEnv + " instead.\n")
	for _, kv := range pairs {
		b.WriteString(kv.Key + "=" + kv.Value + "\n")
	}
	return b.String()
}

var wsIDRE = regexp.MustCompile(`^[a-z0-9][a-z0-9_-]{0,62}$`)

// DashDir is a workspace's own dashboard data folder (wallpaper, settings).
type DashDir struct{ ID, Path string }

// WorkspaceDashboardDirs lists <workspace>/.om/dashboard for every registered workspace that still exists on
// disk, sorted by id.
func WorkspaceDashboardDirs(reg registry.Registry) []DashDir {
	var out []DashDir
	r := reg.Read()
	ids := make([]string, 0, len(r))
	for id := range r {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		p, _ := r[id]["path"].(string)
		if st, err := os.Stat(p); wsIDRE.MatchString(id) && p != "" && err == nil && st.IsDir() {
			out = append(out, DashDir{id, filepath.Join(p, ".om", "dashboard")})
		}
	}
	return out
}

// RenderDashboardMounts mounts each workspace's own dashboard data into the dashboard.
func RenderDashboardMounts(dirs []DashDir) string {
	if len(dirs) == 0 {
		return "# GENERATED by `om core start` — do not edit.\nservices: {}\n"
	}
	var b strings.Builder
	for _, x := range dirs {
		b.WriteString("      - " + ComposePath(x.Path) + ":/workspaces/" + x.ID + ":Z\n")
	}
	return "# GENERATED by `om core start` — do not edit.\nservices:\n  dashboard:\n    volumes:\n" + b.String()
}

// MigrateDashboardData copies dashboard data kept in <state>/data/dashboard/workspaces/<id>/ into the workspace
// (once: only into an empty folder, and the old copy is left in place).
func MigrateDashboardData(d state.Dirs, dirs []DashDir) error {
	for _, x := range dirs {
		if err := os.MkdirAll(x.Path, 0o755); err != nil {
			return err
		}
		old := filepath.Join(d.Data, "dashboard", "workspaces", x.ID)
		if st, err := os.Stat(old); err != nil || !st.IsDir() {
			continue
		}
		if existing, _ := os.ReadDir(x.Path); len(existing) > 0 {
			continue
		}
		entries, err := os.ReadDir(old)
		if err != nil {
			return err
		}
		for _, e := range entries {
			if st, err := os.Stat(filepath.Join(old, e.Name())); err == nil && st.Mode().IsRegular() {
				if err := copyFile(filepath.Join(old, e.Name()), filepath.Join(x.Path, e.Name()), st); err != nil {
					return err
				}
			}
		}
	}
	return nil
}

func copyFile(src, dst string, st os.FileInfo) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	out, err := os.OpenFile(dst, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, st.Mode().Perm())
	if err != nil {
		return err
	}
	if _, err := io.Copy(out, in); err != nil {
		out.Close()
		return err
	}
	if err := out.Close(); err != nil {
		return err
	}
	return os.Chtimes(dst, st.ModTime(), st.ModTime()) // shutil.copy2 keeps the times
}
