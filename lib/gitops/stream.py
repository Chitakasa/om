#!/usr/bin/env python3
"""Raw TCP stream tier logic for 'om': label parsing, port validation, HAProxy config generation,
and stream slot registry."""

from __future__ import annotations

import re
import shutil
import tempfile
from pathlib import Path
from typing import Any

from gitops import core

# Labels for raw TCP services
LABEL_TCP = "om.tcp"
LABEL_TCP_PORT = "om.tcp.port"

# Ports and port ranges reserved by om core or system
RESERVED_EXACT_PORTS = {80, 443, 8080, 8443}
HTTP_PORT_START = 20000
HTTP_PORT_END = 21199  # Covers 20000-20199 (private) and 21000-21199 (public)
STREAM_DEFAULT_START = 22000
STREAM_DEFAULT_END = 22199  # 200 default stream slots: 22000-22199

# HAProxy pinned image digest
HAPROXY_IMAGE = "docker.io/library/haproxy:3.0-alpine@sha256:35114f41284747c8b460babd0c082d5d8e0268218b167240f47d15d0474b718b"

# Directories for stream proxy configs
STREAM_DIR = core.STATE_DIR / "stream"
FRAGMENTS_DIR = STREAM_DIR / "fragments"
EDGE_FRAGMENTS_DIR = FRAGMENTS_DIR / "edge"
ROUTER_FRAGMENTS_DIR = FRAGMENTS_DIR / "router"
EDGE_CONFIG_FILE = STREAM_DIR / "edge.cfg"
ROUTER_CONFIG_FILE = STREAM_DIR / "router.cfg"


def validate_host_port(port: int, edge_http: int = 80, edge_https: int = 443) -> list[str]:
    """Validate an explicit host port. Returns list of problem strings (empty = valid)."""
    problems = []
    if port < 1024:
        problems.append(f"host port {port} is privileged (must be >= 1024)")
    if port > 65535:
        problems.append(f"host port {port} is invalid (must be <= 65535)")
    reserved = RESERVED_EXACT_PORTS | {edge_http, edge_https}
    if port in reserved:
        problems.append(f"host port {port} clashes with core HTTP/HTTPS ports ({', '.join(sorted(map(str, reserved)))})")
    if HTTP_PORT_START <= port <= HTTP_PORT_END:
        problems.append(f"host port {port} clashes with HTTP per-service port range ({HTTP_PORT_START}-{HTTP_PORT_END})")
    if STREAM_DEFAULT_START <= port <= STREAM_DEFAULT_END:
        problems.append(f"host port {port} clashes with default stream port range ({STREAM_DEFAULT_START}-{STREAM_DEFAULT_END})")
    return problems


def parse_stream_meta(labels: dict[str, str], sname: str = "",
                      edge_http: int = 80, edge_https: int = 443) -> tuple[dict[str, Any] | None, list[str]]:
    """Extract stream routing configuration from compose labels:
        om.tcp=<container-port>
        om.tcp.port=<host-port>  (optional)
        dashboard.scope=public   (optional; default private)
        om.log=off               (optional; default on)

    Returns (config, problems). Fail closed: invalid or unreadable label returns (None, problems).
    When om.tcp is not set at all, returns (None, []).
    """
    raw_tcp = labels.get(LABEL_TCP)
    if raw_tcp is None or not str(raw_tcp).strip():
        return None, []

    problems: list[str] = []
    str_val = str(raw_tcp).strip().strip('"').strip("'")

    if not str_val.isdigit():
        problems.append(f"{sname}: {LABEL_TCP} must be an integer port number (got '{raw_tcp}')")
        return None, problems

    container_port = int(str_val)
    if container_port < 1 or container_port > 65535:
        problems.append(f"{sname}: {LABEL_TCP} port {container_port} out of range (1-65535)")
        return None, problems

    host_port: int | None = None
    raw_host_port = labels.get(LABEL_TCP_PORT)
    if raw_host_port is not None and str(raw_host_port).strip():
        str_hp = str(raw_host_port).strip().strip('"').strip("'")
        if not str_hp.isdigit():
            problems.append(f"{sname}: {LABEL_TCP_PORT} must be an integer port number (got '{raw_host_port}')")
            return None, problems
        host_port = int(str_hp)
        port_probs = validate_host_port(host_port, edge_http, edge_https)
        if port_probs:
            for p in port_probs:
                problems.append(f"{sname}: {p}")
            return None, problems

    scope = "public" if labels.get("dashboard.scope", "").strip().lower() == "public" else "private"
    log = "off" if labels.get("om.log", "").strip().lower() == "off" else "on"

    return {
        "container_port": container_port,
        "host_port": host_port,
        "scope": scope,
        "log": log,
    }, []


def base_edge_config() -> str:
    """Base HAProxy configuration for om_stream_edge."""
    return """# om Stream Edge Proxy (om_stream_edge). Generated by om — do not edit.
global
    log stdout format raw local0
    stats socket /tmp/haproxy.sock mode 660 level admin
    maxconn 2048

defaults
    mode tcp
    timeout connect 5s
    timeout client 1h
    timeout server 1h

frontend health
    mode http
    bind /tmp/health.sock mode 660
    monitor-uri /healthz
"""


def base_router_config() -> str:
    """Base HAProxy configuration for om_stream_router."""
    return """# om Stream Router (om_stream_router). Generated by om — do not edit.
global
    log stdout format raw local0
    stats socket /tmp/haproxy.sock mode 660 level admin
    maxconn 2048

defaults
    mode tcp
    timeout connect 5s
    timeout client 1h
    timeout server 1h

resolvers docker
    parse-resolv-conf
    resolve_retries 3
    timeout retry 1s
    hold valid 10s

frontend health
    mode http
    bind /tmp/health.sock mode 660
    monitor-uri /healthz
"""


def render_edge_fragment(ws_id: str, sname: str, host_port: int, log: str = "on") -> str:
    """Render HAProxy fragment for om_stream_edge forwarding host_port to the unix socket."""
    log_opt = "    log global\n    option tcplog\n" if log != "off" else ""
    return f"""# Service: {sname} ({ws_id})
frontend stream_{host_port}
    bind :{host_port}
{log_opt}    default_backend sock_{host_port}

backend sock_{host_port}
    server s1 /run/om-stream/{host_port}.sock
"""


def render_router_fragment(ws_id: str, sname: str, host_port: int, container_port: int) -> str:
    """Render HAProxy fragment for om_stream_router connecting the unix socket to the target container."""
    return f"""# Service: {sname} ({ws_id})
frontend sock_{host_port}
    bind /run/om-stream/{host_port}.sock mode 660
    default_backend target_{host_port}

backend target_{host_port}
    server s1 {ws_id}_{sname}:{container_port} resolvers docker init-addr libc,none check inter 5s
"""


def validate_haproxy_syntax(content: str, runtime: str | None = None) -> list[str]:
    """Validate HAProxy configuration syntax. Uses host haproxy if available, or container engine,
    falling back to strict structural validation."""
    problems: list[str] = []
    haproxy_bin = shutil.which("haproxy")
    if haproxy_bin:
        with tempfile.NamedTemporaryFile("w", encoding="utf-8", suffix=".cfg", delete=False) as tf:
            tf.write(content)
            tf_path = Path(tf.name)
        try:
            tf_path.chmod(0o644)
            r = core.run([haproxy_bin, "-c", "-f", str(tf_path)])
            if r.returncode not in (0, 2):
                err = (r.stderr or r.stdout).strip()
                problems.append(f"HAProxy validation error: {err}")
        finally:
            tf_path.unlink(missing_ok=True)
        return problems

    if runtime and runtime != "om-test-no-engine" and shutil.which(runtime):
        with tempfile.NamedTemporaryFile("w", encoding="utf-8", suffix=".cfg", delete=False) as tf:
            tf.write(content)
            tf_path = Path(tf.name)
        try:
            tf_path.chmod(0o644)
            r = core.run([runtime, "run", "--rm", "-v", f"{tf_path.resolve()}:/tmp/check.cfg:ro,Z",
                          HAPROXY_IMAGE, "/usr/local/sbin/haproxy", "-c", "-f", "/tmp/check.cfg"])
            if r.returncode not in (0, 2):
                err = (r.stderr or r.stdout).strip()
                problems.append(f"HAProxy engine validation error: {err}")
        finally:
            tf_path.unlink(missing_ok=True)
        return problems

    # Python fallback structural check
    VALID_SECTION_DIRECTIVES = {
        "global": {"log", "stats", "maxconn", "user", "group", "chroot", "daemon", "master-worker", "pidfile"},
        "defaults": {"mode", "log", "option", "no", "timeout", "retries", "maxconn"},
        "resolvers": {"nameserver", "parse-resolv-conf", "resolve_retries", "timeout", "hold", "accepted_payload_size"},
        "frontend": {"bind", "mode", "default_backend", "use_backend", "log", "option", "no", "timeout", "monitor-uri", "maxconn"},
        "backend": {"server", "mode", "balance", "timeout", "log", "option", "no", "default-server"},
    }

    sections = set()
    current_section = None
    for n, raw in enumerate(content.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        tokens = line.split()
        head = tokens[0]
        if head in ("global", "defaults", "resolvers", "frontend", "backend"):
            current_section = head
            sec_name = tokens[1] if len(tokens) > 1 else ""
            if head in ("frontend", "backend"):
                sections.add((head, sec_name))
        elif not current_section:
            problems.append(f"line {n}: directive '{head}' outside any section")
        elif head not in VALID_SECTION_DIRECTIVES.get(current_section, set()):
            problems.append(f"line {n}: unknown or invalid directive '{head}' in section '{current_section}'")

    fes = {name for kind, name in sections if kind == "frontend"}
    bes = {name for kind, name in sections if kind == "backend"}
    for fe in fes:
        if fe == "health":
            continue
        expected_be = fe.replace("stream_", "sock_") if fe.startswith("stream_") else fe.replace("sock_", "target_")
        if expected_be not in bes:
            problems.append(f"frontend '{fe}' has no matching backend '{expected_be}'")

    return problems


_FRAGMENT_OWNER_RE = re.compile(r"^# Service: ([a-z0-9-]+) \(([a-z0-9-]+)\)")


def _owned_fragments(directory: Path, ws_id: str) -> list[tuple[Path, str]]:
    """[(fragment file, service)] owned by ws_id, by the header inside the file. Never by file name:
    workspace ids contain '-', so `a-*.cfg` would also match the fragments of workspace `a-b`."""
    out = []
    for p in sorted(directory.glob("*.cfg")):
        try:
            with open(p, encoding="utf-8") as f:
                m = _FRAGMENT_OWNER_RE.match(f.readline())
        except OSError:
            continue
        if m and m.group(2) == ws_id:
            out.append((p, m.group(1)))
    return out


def ensure_stream_configs():
    """Ensure STREAM_DIR and base edge.cfg / router.cfg exist."""
    STREAM_DIR.mkdir(parents=True, exist_ok=True)
    EDGE_FRAGMENTS_DIR.mkdir(parents=True, exist_ok=True)
    ROUTER_FRAGMENTS_DIR.mkdir(parents=True, exist_ok=True)
    if not EDGE_CONFIG_FILE.exists() or EDGE_CONFIG_FILE.is_dir():
        if EDGE_CONFIG_FILE.is_dir():
            shutil.rmtree(EDGE_CONFIG_FILE)
        EDGE_CONFIG_FILE.write_text(base_edge_config(), encoding="utf-8", newline="\n")
    if not ROUTER_CONFIG_FILE.exists() or ROUTER_CONFIG_FILE.is_dir():
        if ROUTER_CONFIG_FILE.is_dir():
            shutil.rmtree(ROUTER_CONFIG_FILE)
        ROUTER_CONFIG_FILE.write_text(base_router_config(), encoding="utf-8", newline="\n")


def assemble_stream_configs(runtime: str | None = None) -> tuple[str, str, list[str]]:
    """Assemble all edge and router fragments into full configs and validate them.
    Returns (edge_content, router_content, problems)."""
    ensure_stream_configs()

    edge_parts = [base_edge_config().strip()]
    for p in sorted(EDGE_FRAGMENTS_DIR.glob("*.cfg")):
        text = p.read_text(encoding="utf-8").strip()
        if text:
            edge_parts.append(text)
    edge_full = "\n\n".join(edge_parts) + "\n"

    router_parts = [base_router_config().strip()]
    for p in sorted(ROUTER_FRAGMENTS_DIR.glob("*.cfg")):
        text = p.read_text(encoding="utf-8").strip()
        if text:
            router_parts.append(text)
    router_full = "\n\n".join(router_parts) + "\n"

    problems = []
    problems.extend(validate_haproxy_syntax(edge_full, runtime))
    problems.extend(validate_haproxy_syntax(router_full, runtime))
    return edge_full, router_full, problems


def reload_stream(runtime: str) -> bool:
    """Reload running om_stream_edge and om_stream_router using SIGUSR2."""
    ok = True
    for c in (core.STREAM_EDGE, core.STREAM_ROUTER):
        if core.container_running(runtime, c):
            r = core.run([runtime, "kill", "-s", "USR2", c])
            if r.returncode != 0:
                ok = False
    return ok


def sync_stream_routes(ws_id: str, stream_services: dict[str, dict], runtime: str) -> bool:
    """Update stream fragments for workspace `ws_id`, assemble and validate candidate configs.
    If valid: write configs atomically and reload running stream containers.
    If invalid: leave existing live configs untouched.
    """
    ensure_stream_configs()
    with core.file_lock(STREAM_DIR / "stream.lock"):
        # Write new / updated fragments for this workspace
        for sname, meta in stream_services.items():
            hp = meta["host_port"]
            cp = meta["container_port"]
            log = meta.get("log", "on")

            edge_frag = render_edge_fragment(ws_id, sname, hp, log)
            router_frag = render_router_fragment(ws_id, sname, hp, cp)

            (EDGE_FRAGMENTS_DIR / f"{ws_id}-{sname}.cfg").write_text(edge_frag, encoding="utf-8", newline="\n")
            (ROUTER_FRAGMENTS_DIR / f"{ws_id}-{sname}.cfg").write_text(router_frag, encoding="utf-8", newline="\n")

        # Prune fragments of ws_id for services that no longer declare om.tcp
        for d in (EDGE_FRAGMENTS_DIR, ROUTER_FRAGMENTS_DIR):
            for p, sname in _owned_fragments(d, ws_id):
                if sname not in stream_services:
                    p.unlink(missing_ok=True)

        # Assemble and validate
        edge_full, router_full, problems = assemble_stream_configs(runtime)
        if problems:
            # Leave live configs untouched (fail closed)
            for pr in problems:
                print(f"  \033[31m✗ Stream config validation failed: {pr}\033[0m")
            return False

        # Apply valid configs atomically
        core.write_atomic(EDGE_CONFIG_FILE, edge_full)
        core.write_atomic(ROUTER_CONFIG_FILE, router_full)
        reload_stream(runtime)
        return True


def prune_stream_fragments(ws_id: str, runtime: str) -> bool:
    """Remove fragments of workspace `ws_id`, rebuild and reload stream configs."""
    ensure_stream_configs()
    with core.file_lock(STREAM_DIR / "stream.lock"):
        changed = False
        for d in (EDGE_FRAGMENTS_DIR, ROUTER_FRAGMENTS_DIR):
            for p, _ in _owned_fragments(d, ws_id):
                p.unlink(missing_ok=True)
                changed = True

        if not changed:
            return False

        edge_full, router_full, problems = assemble_stream_configs(runtime)
        if not problems:
            core.write_atomic(EDGE_CONFIG_FILE, edge_full)
            core.write_atomic(ROUTER_CONFIG_FILE, router_full)
            reload_stream(runtime)
        return True
