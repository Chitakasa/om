#!/usr/bin/env python3
"""The door (om_wg): WireGuard peers rendered from the verified access-file head.

The server key lives in $OM_STATE_DIR/door/ (0600, mounted read-only into om_wg). Keys are
made by `wg` inside the door image — om writes no cryptography. Each device gets one /32 in
the door subnet; WireGuard's cryptokey routing makes that address proof of the device.
"""

import hashlib
import os

from gitops.core import CORE_DIR, STATE_DIR, load_settings, run

DOOR = "om_wg"
DOOR_DIR = STATE_DIR / "door"


def image() -> str:
    """Local image tag = hash of its build files, so any change to core/door rebuilds it."""
    h = hashlib.sha256()
    for f in sorted((CORE_DIR / "door").iterdir()):
        if f.is_file():
            h.update(f.name.encode() + b"\0" + f.read_bytes())
    return f"localhost/om-door:{h.hexdigest()[:12]}"


IMAGE = image()


def settings() -> dict:
    s = load_settings()
    return {"subnet": s.get("OM_DOOR_SUBNET", "10.77.0.0/24"), "port": int(s.get("OM_DOOR_PORT", "51820") or 51820)}


def _wg(runtime: str, *args: str, stdin: str | None = None) -> str:
    """Run `wg` (key tools only) in a throwaway door-image container with no network."""
    cmd = [runtime, "run", "--rm", "-i", "--network", "none", "--entrypoint", "wg", image(), *args]
    r = run(cmd, input=stdin)
    if r.returncode != 0:
        raise RuntimeError(f"wg {args[0]} failed: {(r.stderr or r.stdout).strip()[-300:]}")
    return r.stdout.strip()


def genkey(runtime: str) -> tuple[str, str]:
    priv = _wg(runtime, "genkey")
    return priv, _wg(runtime, "pubkey", stdin=priv + "\n")


def server_public_key(runtime: str) -> str:
    """Create the server key once; return its public key."""
    DOOR_DIR.mkdir(parents=True, exist_ok=True)
    key = DOOR_DIR / "server.key"
    if not key.exists():
        priv, _ = genkey(runtime)
        key.write_text(priv + "\n", encoding="utf-8", newline="\n")
        os.chmod(key, 0o600)
    return _wg(runtime, "pubkey", stdin=key.read_text(encoding="utf-8"))


def render(head: dict | None):
    """wg0.conf for `wg setconf`: the server key and one peer per enrolled device."""
    DOOR_DIR.mkdir(parents=True, exist_ok=True)
    key = (DOOR_DIR / "server.key").read_text(encoding="utf-8").strip() if (DOOR_DIR / "server.key").exists() else ""
    lines = ["# Generated by om from the signed access file — do not edit.", "[Interface]",
             f"ListenPort = {settings()['port']}"]
    if key:
        lines.append(f"PrivateKey = {key}")
    for name, d in sorted(((head or {}).get("devices") or {}).items()):
        lines += ["", f"# {name}", "[Peer]", f"PublicKey = {d['public_key']}", f"AllowedIPs = {d['address']}/32"]
    path = DOOR_DIR / "wg0.conf"
    tmp = DOOR_DIR / ".wg0.conf.tmp"
    tmp.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    os.chmod(tmp, 0o600)
    os.replace(tmp, path)


def reload(runtime: str) -> bool:
    return run([runtime, "exec", DOOR, "wg", "syncconf", "wg0", "/etc/om-door/wg0.conf"]).returncode == 0


def client_config(head: dict, name: str, private_key: str, endpoint: str) -> str:
    d, door = head["devices"][name], head["door"]
    return "\n".join([
        "[Interface]", f"# om device {name}", f"PrivateKey = {private_key}", f"Address = {d['address']}/32",
        f"DNS = {door['address']}", "",
        "[Peer]", f"PublicKey = {door['public_key']}", f"Endpoint = {endpoint}:{settings()['port']}",
        # Only the door's own address goes through the tunnel; the device's other traffic is untouched.
        f"AllowedIPs = {door['address']}/32", "PersistentKeepalive = 25", ""])


def qr(runtime: str, text: str) -> str:
    r = run([runtime, "run", "--rm", "-i", "--network", "none", "--entrypoint", "qrencode", IMAGE, "-t", "ansiutf8"], input=text)
    return r.stdout if r.returncode == 0 else ""


def peers_seen(runtime: str) -> dict:
    """{public key: latest handshake epoch} from the running door."""
    r = run([runtime, "exec", DOOR, "wg", "show", "wg0", "latest-handshakes"])
    out = {}
    for line in r.stdout.splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[1].isdigit():
            out[parts[0]] = int(parts[1])
    return out
