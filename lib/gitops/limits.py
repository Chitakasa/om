#!/usr/bin/env python3
"""Resource limits from labels, as a compose override om passes at start:

  om.mem=256m    memory limit (k, m or g)
  om.pids=200    most processes and threads
  om.cpus=0.5    CPU cores

A label that does not parse is reported and ignored (the service runs without that limit).
"""

import hashlib
import json
import re
from pathlib import Path

from gitops.core import STATE_DIR
from gitops.policy import _labels

OVERRIDE_DIR = STATE_DIR / "limits" / "overrides"
MEM_RE = re.compile(r"^([1-9][0-9]{0,8})([kmg])b?$", re.I)
PIDS_RE = re.compile(r"^[1-9][0-9]{0,5}$")
CPUS_RE = re.compile(r"^(?:[0-9]+\.?[0-9]*|\.[0-9]+)$")


def parse(labels: dict) -> tuple[dict, list]:
    """({compose key: value}, [problems]) for one service's om.mem / om.pids / om.cpus labels."""
    out, problems = {}, []
    raw = str(labels.get("om.mem", "")).strip()
    if raw:
        m = MEM_RE.match(raw)
        if m:
            out["mem_limit"] = m.group(1) + m.group(2).lower()
        else:
            problems.append(f"om.mem={raw} (use a number with k, m or g, e.g. 256m)")
    raw = str(labels.get("om.pids", "")).strip()
    if raw:
        if PIDS_RE.match(raw):
            out["pids_limit"] = int(raw)
        else:
            problems.append(f"om.pids={raw} (use a whole number, e.g. 200)")
    raw = str(labels.get("om.cpus", "")).strip()
    if raw:
        if CPUS_RE.match(raw) and 0.01 <= float(raw) <= 256:
            out["cpus"] = float(raw)
        else:
            problems.append(f"om.cpus={raw} (use cores between 0.01 and 256, e.g. 0.5)")
    return out, problems


def write_override(ws: str, project_dir: Path, cfg: dict | None) -> tuple:
    """(override file or None, [problems]) for the services of one compose file."""
    wanted, problems = {}, []
    for name, svc in ((cfg or {}).get("services") or {}).items():
        limits, bad = parse(_labels(svc or {}))
        problems += [f"{name}: {p}" for p in bad]
        if limits:
            wanted[name] = limits
    path = OVERRIDE_DIR / f"{ws}-{hashlib.sha256(str(project_dir).encode()).hexdigest()[:12]}.yml"
    if not wanted:
        path.unlink(missing_ok=True)
        return None, problems
    lines = ["# Generated by om from om.mem / om.pids / om.cpus labels. Do not edit.", "services:"]
    for name in sorted(wanted):
        lines.append(f"  {json.dumps(name)}:")
        lines += [f"    {key}: {json.dumps(value)}" for key, value in sorted(wanted[name].items())]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return path, problems
