#!/usr/bin/env python3
"""Outbound allow-list proxy (om_egress, Squid) — see docs/adr/0002-egress-proxy.md and 0006-source-ip-egress.md.

Workspace networks are internal, so a service's only way out is om_egress, and only to the hosts its
`om.egress` label lists. Identity is established by deterministic static source IP assigned to the
container on its project network:

  squid.conf          fixed base: deny private ranges, CONNECT only to 443, no cache, deny all
  acl/<ws>.conf       per-service rules: `acl s_<id> src <ip>/32` + `dstdomain` allow rules
  ips/<ws>.json       allocated static IPs per service (0600)
  learn/<ws>_<svc>.json  learned host records and TTL tracking (0600)
"""

import hashlib
import ipaddress
import json
import os
import re
import time
from pathlib import Path

from gitops.core import CORE_DIR, STATE_DIR, EDGE, run, write_private
from gitops.network import service_project_network_key

EGRESS = "om_egress"
IMAGE_DIR = CORE_DIR / "egress"
EGRESS_DIR = STATE_DIR / "egress"
IPS_DIR = EGRESS_DIR / "ips"
LEARN_DIR = EGRESS_DIR / "learn"
PORT = 3128
HOST_RE = re.compile(r"^(\*\.)?([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z][a-z0-9-]{0,61}[a-z0-9]$")
INTERNET = "internet"
LEARN = "learn"  # allow any public host and record it, to find out what a service needs
AUDIT = "audit"  # allow any public host permanently and continuously record it
DEFAULT_LEARN_TTL = 86400  # 24 hours

BASE_CONF = f"""# Generated by om — do not edit. Rules per service: acl/<workspace>.conf
http_port {PORT}
# Squid sizes its tables to the open-file limit; the engine's default (524288) costs ~70 MB of RAM
max_filedescriptors 4096
pid_filename /tmp/squid.pid
shutdown_lifetime 1 seconds
cache deny all
cache_mem 0
cache_store_log none
coredump_dir /tmp
access_log stdio:/dev/stdout
cache_log stdio:/dev/stderr
forwarded_for delete

# Never the host, the core, another workspace or the LAN — even for an allowed name
# that resolves there (DNS rebinding). No ::ffff:0:0/96 here: Squid reads it as 0.0.0.0/0 and would
# refuse every address; it already treats an IPv4-mapped address as the IPv4 one the ranges above cover.
acl to_private dst 0.0.0.0/8 10.0.0.0/8 100.64.0.0/10 127.0.0.0/8 169.254.0.0/16 172.16.0.0/12 192.0.0.0/24 192.0.2.0/24 192.168.0.0/16 198.18.0.0/15 198.51.100.0/24 203.0.113.0/24 224.0.0.0/3 ::/128 ::1/128 64:ff9b::/96 100::/64 2001:db8::/32 2002::/16 fc00::/7 fe80::/10 fec0::/10 ff00::/8
acl SSL_ports port 443
acl Safe_ports port 80 443
acl CONNECT method CONNECT
http_access deny !Safe_ports
http_access deny CONNECT !SSL_ports
http_access deny to_private

include /etc/om-egress/acl/*.conf

http_access deny all
"""

JVM_IMAGE_KEYWORDS = (
    "openjdk", "temurin", "corretto", "zulu", "graalvm", "java",
    "suwayomi", "minecraft", "paper", "purpur", "spigot", "forge", "fabric",
    "elasticsearch", "logstash", "solr", "jenkins", "kafka", "spark", "trino", "hadoop"
)


def image() -> str:
    """Local tag of the proxy image: a hash of core/egress/, so editing the Containerfile builds a new one."""
    h = hashlib.sha256()
    for f in sorted(IMAGE_DIR.iterdir()) if IMAGE_DIR.is_dir() else []:
        if f.is_file():
            h.update(f.name.encode() + b"\0" + f.read_bytes())
    return f"localhost/om-egress:{h.hexdigest()[:12]}"


def ensure_image(runtime: str) -> bool:
    """Build the proxy image if this engine does not have it yet (Squid on Alpine, from core/egress/)."""
    if run([runtime, "image", "inspect", image()]).returncode == 0:
        return True
    r = run([runtime, "build", "-q", "-t", image(), "-f", str(IMAGE_DIR / "Containerfile"), str(IMAGE_DIR)])
    if r.returncode != 0:
        print(f"\033[31m✗ could not build the egress proxy image: {(r.stderr or r.stdout).strip()[-400:]}\033[0m")
    return r.returncode == 0


def valid_host(h: str) -> bool:
    return bool(HOST_RE.match(h))


def parse_label(value: str) -> list[str] | str | None:
    """`om.egress` → list of hosts, INTERNET, LEARN, AUDIT, or None (absent). Invalid names are kept out."""
    if value is None or not str(value).strip():
        return None
    items = [v.strip().lower() for v in str(value).split(",") if v.strip()]
    if INTERNET in items:
        return INTERNET
    if AUDIT in items or "monitor" in items:
        return AUDIT
    if LEARN in items:
        return LEARN
    return [h for h in items if valid_host(h)]


def parse_ttl(ttl_str: str | None) -> int:
    """Convert a human TTL string ('24h', '30m', '7d', '3600s', 'never') into seconds (default 86400, 0 for never)."""
    if not ttl_str or not str(ttl_str).strip():
        return DEFAULT_LEARN_TTL
    s = str(ttl_str).strip().lower()
    if s in ("0", "never", "off", "none", "permanent", "infinite", "inf"):
        return 0
    try:
        if s.endswith("d"):
            return int(float(s[:-1]) * 86400)
        if s.endswith("h"):
            return int(float(s[:-1]) * 3600)
        if s.endswith("m"):
            return int(float(s[:-1]) * 60)
        if s.endswith("s"):
            return int(float(s[:-1]))
        return int(float(s))
    except ValueError:
        return DEFAULT_LEARN_TTL


def _acl_id(ws: str, svc: str) -> str:
    safe = re.sub(r"[^a-zA-Z0-9]", "_", f"{ws}_{svc}")
    return f"{safe}_{hashlib.sha256(f'{ws}/{svc}'.encode()).hexdigest()[:8]}"


def user_name(ws: str, svc: str) -> str:
    return f"{ws}.{svc}"


def _load_ips(ws: str) -> dict[str, str]:
    p = IPS_DIR / f"{ws}.json"
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def _save_ips(ws: str, ips: dict[str, str]):
    IPS_DIR.mkdir(parents=True, exist_ok=True)
    _write(IPS_DIR / f"{ws}.json", json.dumps(ips, indent=2, sort_keys=True) + "\n", private=True)


def all_service_ips() -> dict[str, str]:
    """Map client IP address -> 'ws.svc' across all registered workspaces."""
    out = {}
    if not IPS_DIR.is_dir():
        return out
    for f in sorted(IPS_DIR.glob("*.json")):
        ws = f.stem
        for svc, ip in _load_ips(ws).items():
            if ip:
                out[ip] = f"{ws}.{svc}"
    return out


def allocate_service_ip(ws: str, svc: str, subnet: str | None = None) -> str:
    """Get or allocate a deterministic static IP for svc in subnet (e.g. '10.89.12.0/24')."""
    ips = _load_ips(ws)
    if subnet:
        try:
            nw = ipaddress.ip_network(subnet)
        except ValueError:
            nw = None
    else:
        # Fallback when subnet cannot be inspected (e.g. offline tests).
        # Deterministic /24 based on hash of ws.
        h = int(hashlib.sha256(ws.encode()).hexdigest()[:4], 16) % 200 + 10
        nw = ipaddress.ip_network(f"10.89.{h}.0/24")

    current = ips.get(svc)
    if current and nw and ipaddress.ip_address(current) in nw:
        return current

    used = {ipaddress.ip_address(ip) for ip in ips.values() if nw and ipaddress.ip_address(ip) in nw}
    start_idx = min(50, max(2, nw.num_addresses - 10))
    allocated_ip = None
    for i in range(start_idx, nw.num_addresses - 2):
        candidate = nw[i]
        if candidate not in used:
            allocated_ip = str(candidate)
            break
    if not allocated_ip:
        allocated_ip = str(nw[nw.num_addresses - 2])

    ips[svc] = allocated_ip
    _save_ips(ws, ips)
    return allocated_ip


def _learn_file(ws: str, svc: str) -> Path:
    safe = re.sub(r"[^a-zA-Z0-9_-]", "_", f"{ws}_{svc}")
    return LEARN_DIR / f"{safe}.json"


def load_learn(ws: str, svc: str) -> dict:
    p = _learn_file(ws, svc)
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def save_learn(ws: str, svc: str, data: dict):
    LEARN_DIR.mkdir(parents=True, exist_ok=True)
    _write(_learn_file(ws, svc), json.dumps(data, indent=2, sort_keys=True) + "\n", private=True)


def init_learn(ws: str, svc: str, ttl_sec: int = DEFAULT_LEARN_TTL, update_ttl: bool = False) -> dict:
    """Create the learn record. update_ttl: the caller knows the service's label (write_override), so a
    changed TTL replaces the stored one and restarts the window; otherwise an existing record is kept."""
    data = load_learn(ws, svc)
    now = int(time.time())
    if not data or not data.get("started_at"):
        data = {
            "started_at": now,
            "ttl": ttl_sec,
            "hosts": {},
        }
        save_learn(ws, svc, data)
    elif update_ttl and data.get("ttl", DEFAULT_LEARN_TTL) != ttl_sec:
        data["ttl"], data["started_at"] = ttl_sec, now
        save_learn(ws, svc, data)
    return data


def is_learn_expired(ws: str, svc: str) -> bool:
    data = load_learn(ws, svc)
    if not data or not data.get("started_at"):
        return False
    ttl = data.get("ttl", DEFAULT_LEARN_TTL)
    if ttl == 0:
        return False
    now = time.time()
    return now >= (data["started_at"] + ttl)


def learn_remaining(ws: str, svc: str) -> int:
    """Seconds left in learn mode for svc, -1 if permanent, or 0 if expired/not learning."""
    data = load_learn(ws, svc)
    if not data or not data.get("started_at"):
        return 0
    ttl = data.get("ttl", DEFAULT_LEARN_TTL)
    if ttl == 0:
        return -1
    now = int(time.time())
    expires = data["started_at"] + ttl
    return max(0, expires - now)


def record_learned_host(ws: str, svc: str, host: str, ts: float | None = None):
    data = load_learn(ws, svc)
    if not data:
        data = {"started_at": int(ts or time.time()), "ttl": DEFAULT_LEARN_TTL, "hosts": {}}
    hosts = data.setdefault("hosts", {})
    entry = hosts.setdefault(host.lower(), {"first_seen": int(ts or time.time()), "count": 0})
    if ts is not None:
        if ts <= entry.get("last_ts", 0):  # a log line already counted (the same log is read again)
            return
        entry["last_ts"] = ts
    entry["count"] += 1
    save_learn(ws, svc, data)


def is_jvm_service(svc: dict) -> bool:
    """Return True if service runs Java/JVM and needs JAVA_TOOL_OPTIONS proxy injection."""
    labels = svc.get("labels") or {}
    if isinstance(labels, list):
        labels = dict(l.split("=", 1) if "=" in l else (l, "") for l in labels)
    if labels.get("om.egress.jvm", "").strip().lower() in ("true", "1", "yes"):
        return True
    if labels.get("om.jvm", "").strip().lower() in ("true", "1", "yes"):
        return True
    image = str(svc.get("image", "")).lower()
    if any(k in image for k in JVM_IMAGE_KEYWORDS):
        return True
    env = svc.get("environment") or {}
    env_keys = set(env.keys()) if isinstance(env, dict) else {e.split("=")[0] for e in env if "=" in str(e)}
    if any(k in env_keys for k in ("JAVA_TOOL_OPTIONS", "_JAVA_OPTIONS", "JAVA_OPTS")):
        return True
    return False


def merge_java_proxy_opts(existing: str | None, host: str = EGRESS, port: int = PORT, non_proxy: str = "localhost|127.0.0.1|::1") -> str:
    """Merge JVM system properties for HTTP and HTTPS proxy into JAVA_TOOL_OPTIONS."""
    tokens = str(existing or "").strip()
    needed = [
        f"-Dhttp.proxyHost={host}",
        f"-Dhttp.proxyPort={port}",
        f"-Dhttps.proxyHost={host}",
        f"-Dhttps.proxyPort={port}",
        f"-Dhttp.nonProxyHosts={non_proxy}",
    ]
    to_add = [opt for opt in needed if opt.split("=")[0] not in tokens]
    if not to_add:
        return tokens
    return (tokens + " " + " ".join(to_add)).strip()


def render_acl(ws: str, services: dict, ips: dict | None = None) -> str:
    """Squid rules for one workspace: {svc: [hosts] | INTERNET | LEARN | AUDIT} using source IP identity."""
    lines = [f"# Generated by om for workspace {ws} — do not edit."]
    if ips is None:
        ips = _load_ips(ws)
    for svc, hosts in sorted(services.items()):
        ip = ips.get(svc)
        if not ip:
            ip = allocate_service_ip(ws, svc)
        aid = _acl_id(ws, svc)
        lines.append(f"acl s_{aid} src {ip}/32")
        if hosts == INTERNET:
            lines.append(f"http_access allow s_{aid}")
        elif hosts == AUDIT:
            lines.append(f"http_access allow s_{aid}")
        elif hosts == LEARN:
            if is_learn_expired(ws, svc):
                lines.append(f"# learn mode expired for {svc} ({ip})")
                try:
                    from gitops import notify
                    notify.notify(
                        f"Egress learn mode expired: {ws}/{svc}",
                        f"Service '{ws}/{svc}' learn mode has expired and fallen back to deny-all. Run `om egress log {svc} --apply` to allow discovered hosts.",
                        key=f"egress-learn-expired:{ws}:{svc}",
                    )
                except Exception:
                    pass
            else:
                lines.append(f"http_access allow s_{aid}")
        elif hosts:
            doms = " ".join(h[1:] if h.startswith("*.") else h for h in hosts)  # *.x → .x (x and below)
            lines.append(f"acl d_{aid} dstdomain {doms}")
            lines.append(f"http_access allow s_{aid} d_{aid}")
    return "\n".join(lines) + "\n"


def ensure_base():
    (EGRESS_DIR / "acl").mkdir(parents=True, exist_ok=True)
    IPS_DIR.mkdir(parents=True, exist_ok=True)
    LEARN_DIR.mkdir(parents=True, exist_ok=True)
    _write(EGRESS_DIR / "squid.conf", BASE_CONF)
    placeholder = EGRESS_DIR / "acl" / "00-none.conf"  # the include glob must match something
    if not placeholder.exists():
        _write(placeholder, "# placeholder\n")


def _write(path, text, private=False):
    if private:
        write_private(path, text)
        return
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8", newline="\n")
    os.replace(tmp, path)


def proxy_url(ws: str = "", svc: str = "", token: str = "") -> str:
    """Return the plain proxy URL without credentials (source IP provides identity)."""
    return f"http://{EGRESS}:{PORT}"


def render_workspace(runtime: str, ws: str, services: dict, prune: bool = True, subnets: dict | None = None) -> dict:
    """Write source-IP rules for one workspace, reload the proxy, return {svc: proxy_url}."""
    ensure_base()
    ips = _load_ips(ws)
    subnets = subnets or {}

    if prune:
        ips = {svc: ip for svc, ip in ips.items() if svc in services}
    else:
        services = {**_load_rules(ws), **services}

    for svc in services:
        subnet = subnets.get(svc)
        if not ips.get(svc):
            ips[svc] = allocate_service_ip(ws, svc, subnet)
        if services[svc] in (LEARN, AUDIT):
            ttl_val = 0 if services[svc] == AUDIT else DEFAULT_LEARN_TTL
            init_learn(ws, svc, ttl_sec=ttl_val)

    _save_ips(ws, ips)
    _write(EGRESS_DIR / f"{ws}.rules", json.dumps(services, sort_keys=True) + "\n", private=True)

    acl = EGRESS_DIR / "acl" / f"{ws}.conf"
    if services:
        _write(acl, render_acl(ws, services, ips))
    else:
        acl.unlink(missing_ok=True)

    reload(runtime)
    return {svc: proxy_url() for svc in services}


def _load_rules(ws: str) -> dict:
    try:
        return json.loads((EGRESS_DIR / f"{ws}.rules").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        # Backward compatibility check
        old_path = EGRESS_DIR / "creds" / f"{ws}.rules"
        try:
            return json.loads(old_path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return {}


def write_override(ws: str, project: str, cfg: dict, proxy_urls: dict | None = None, subnet: str | None = None, ips: dict | None = None):
    """Compose override giving each egress service its proxy settings and static IP."""
    services = (cfg or {}).get("services") or {}
    # If proxy_urls is provided, match against it; otherwise check om.egress labels
    if proxy_urls is not None:
        mine = {s: proxy_urls[s] for s in services if s in proxy_urls}
    else:
        mine = {s: proxy_url() for s, svc in services.items() if parse_label((svc.get("labels") or {}).get("om.egress") if isinstance(svc.get("labels"), dict) else None)}
    path = EGRESS_DIR / "overrides" / f"{ws}-{hashlib.sha256(project.encode()).hexdigest()[:12]}.yml"
    if not mine:
        path.unlink(missing_ok=True)
        return None

    assigned_ips = ips if ips is not None else _load_ips(ws)
    local = sorted({"localhost", "127.0.0.1", "::1"} | set(services)
                   | {str(s.get("container_name")) for s in services.values() if s and s.get("container_name")})
    lines = ["# Generated by om — proxy settings for services with om.egress. Do not edit.", "services:"]
    for svc, url in sorted(mine.items()):
        svc_dict = services.get(svc) or {}
        ip = assigned_ips.get(svc) or allocate_service_ip(ws, svc, subnet)
        net_key = service_project_network_key(cfg, svc)

        labels = svc_dict.get("labels") or {}
        if isinstance(labels, list):
            labels = dict(l.split("=", 1) if "=" in l else (l, "") for l in labels)
        lbl = parse_label(labels.get("om.egress"))
        if lbl in (LEARN, AUDIT):
            ttl_val = 0 if lbl == AUDIT else parse_ttl(labels.get("om.egress.learn_ttl"))
            init_learn(ws, svc, ttl_sec=ttl_val, update_ttl=True)

        lines.append(f"  {json.dumps(svc)}:")
        lines.append("    environment:")
        for k in ("HTTP_PROXY", "HTTPS_PROXY", "http_proxy", "https_proxy"):
            lines.append(f"      {k}: {json.dumps(url)}")
        for k in ("NO_PROXY", "no_proxy"):
            lines.append(f"      {k}: {json.dumps(','.join(local))}")

        if is_jvm_service(svc_dict):
            existing_env = svc_dict.get("environment") or {}
            existing_java = ""
            if isinstance(existing_env, dict):
                existing_java = existing_env.get("JAVA_TOOL_OPTIONS", "")
            elif isinstance(existing_env, list):
                for e in existing_env:
                    if str(e).startswith("JAVA_TOOL_OPTIONS="):
                        existing_java = str(e).split("=", 1)[1]
            merged_java = merge_java_proxy_opts(existing_java, EGRESS, PORT, "|".join(local))
            lines.append(f"      JAVA_TOOL_OPTIONS: {json.dumps(merged_java)}")

        lines.append("    networks:")
        lines.append(f"      {net_key}:")
        lines.append(f"        ipv4_address: {json.dumps(ip)}")

    path.parent.mkdir(parents=True, exist_ok=True)
    _write(path, "\n".join(lines) + "\n", private=True)
    return path


# Squid native access log: time elapsed client code/status bytes method URL user hierarchy type
_LOG_RE = re.compile(r"^(\d+\.\d+)\s+\d+\s+(\S+)\s+(\S+)\s+\d+\s+(\S+)\s+(\S+)\s+(\S+)")


def denied_hosts(log_text: str, ips: dict | None = None) -> dict:
    """{"ws.svc": {host, …}} for requests the proxy refused (403)."""
    return _hosts(log_text, lambda code: code == "TCP_DENIED/403", ips=ips)


def used_hosts(log_text: str, ips: dict | None = None) -> dict:
    """{"ws.svc": {host, …}} for requests the proxy let through (learn and audit modes record these)."""
    return _hosts(log_text, lambda code: not code.startswith("TCP_DENIED"), ips=ips)


def _hosts(log_text: str, keep, ips: dict | None = None) -> dict:
    out = {}
    ip_map = ips if ips is not None else all_service_ips()
    for line in log_text.splitlines():
        m = _LOG_RE.match(line.strip())
        if not m:
            continue
        ts_str, client_ip, code, method, url, user = m.groups()
        if not keep(code):
            continue

        service_key = user if user != "-" else ip_map.get(client_ip)
        if not service_key:
            continue

        host = url.split(":", 1)[0] if method == "CONNECT" else url.split("://", 1)[-1].split("/", 1)[0].split(":", 1)[0]
        host = host.lower().strip()
        if not host:
            continue

        out.setdefault(service_key, set()).add(host)

        # Update learn tracking if request was allowed and the service is learning or auditing
        if not code.startswith("TCP_DENIED") and "." in service_key:
            ws, _, svc = service_key.partition(".")
            if _load_rules(ws).get(svc) in (LEARN, AUDIT):
                record_learned_host(ws, svc, host, float(ts_str))
    return out


def suggestion(current, new_hosts) -> str:
    """The om.egress value that adds new_hosts to what the service lists today."""
    have = [] if current in (None, LEARN, AUDIT, INTERNET) else list(current)
    return ",".join(have + sorted(h for h in new_hosts if h not in have))


def find_service_span(text: str, svc: str) -> tuple[int, int, int] | None:
    lines = text.splitlines(keepends=True)
    in_services = False
    svc_start_idx = None
    svc_indent = None

    pos = 0
    line_spans = []
    for line in lines:
        start = pos
        pos += len(line)
        line_spans.append((start, pos, line))

    for i, (start, end, line) in enumerate(line_spans):
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if re.match(r"^services:\s*(?:#.*)?$", line):
            in_services = True
            continue
        if in_services:
            m_svc = re.match(rf"^([ \t]+){re.escape(svc)}:\s*(?:#.*)?$", line)
            if m_svc:
                svc_start_idx = i
                svc_indent = len(m_svc.group(1))
                break
            if not line.startswith(" ") and not line.startswith("\t"):
                in_services = False

    if svc_start_idx is None or svc_indent is None:
        return None

    svc_end_idx = len(line_spans)
    for j in range(svc_start_idx + 1, len(line_spans)):
        start, end, line = line_spans[j]
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        indent_len = len(line) - len(line.lstrip(" \t"))
        if indent_len <= svc_indent:
            svc_end_idx = j
            break

    start_char = line_spans[svc_start_idx][0]
    end_char = line_spans[svc_end_idx - 1][1] if svc_end_idx > 0 else len(text)
    return (start_char, end_char, svc_indent)


def apply_egress_label(compose_path: Path, svc: str, new_hosts: set[str] | list[str]) -> bool:
    """Update om.egress label in compose_path for svc with new_hosts."""
    try:
        text = compose_path.read_text(encoding="utf-8")
    except OSError:
        return False

    span = find_service_span(text, svc)
    if not span:
        return False
    start_char, end_char, svc_indent = span
    svc_block = text[start_char:end_char]

    m_list = re.search(r'^([ \t]*-\s*["\']?)om\.egress=([^"\'\r\n]+)(["\']?)', svc_block, re.MULTILINE)
    m_dict = re.search(r'^([ \t]*om\.egress:\s*["\']?)([^"\'\r\n]+)(["\']?)', svc_block, re.MULTILINE)

    if m_list:
        current_val = m_list.group(2).strip()
        sugg = suggestion(parse_label(current_val), new_hosts)
        pfx = m_list.group(1)
        if pfx.endswith('"') or pfx.endswith("'"):
            q = pfx[-1]
            base_pfx = pfx[:-1]
            rep = f"{base_pfx}{q}om.egress={sugg}{q}"
        else:
            rep = f'{pfx}"om.egress={sugg}"'
        new_svc_block = svc_block[:m_list.start()] + rep + svc_block[m_list.end():]
    elif m_dict:
        current_val = m_dict.group(2).strip()
        sugg = suggestion(parse_label(current_val), new_hosts)
        pfx = m_dict.group(1)
        if pfx.endswith('"') or pfx.endswith("'"):
            q = pfx[-1]
            base_pfx = pfx[:-1]
            rep = f"{base_pfx}{q}{sugg}{q}"
        else:
            rep = f'{pfx}"{sugg}"'
        new_svc_block = svc_block[:m_dict.start()] + rep + svc_block[m_dict.end():]
    else:
        m_labels = re.search(r"^([ \t]+)labels:\s*(?:#.*)?$", svc_block, re.MULTILINE)
        sugg = suggestion(None, new_hosts)
        if m_labels:
            lbl_line_end = svc_block.find("\n", m_labels.start()) + 1
            indent = " " * (len(m_labels.group(1)) + 2)
            rep = f'{indent}- "om.egress={sugg}"\n'
            new_svc_block = svc_block[:lbl_line_end] + rep + svc_block[lbl_line_end:]
        else:
            first_line_end = svc_block.find("\n") + 1
            indent = " " * (svc_indent + 2)
            rep = f'{indent}labels:\n{indent}  - "om.egress={sugg}"\n'
            new_svc_block = svc_block[:first_line_end] + rep + svc_block[first_line_end:]

    new_text = text[:start_char] + new_svc_block + text[end_char:]
    compose_path.write_text(new_text, encoding="utf-8", newline="\n")
    return True


def reload(runtime: str) -> bool:
    r = run([runtime, "exec", EGRESS, "squid", "-k", "reconfigure", "-f", "/etc/om-egress/squid.conf"])
    return r.returncode == 0
