#!/usr/bin/env python3
"""Workspace and per-project networks, and edge proxy reloads for the om substrate."""

import hashlib
import json
import re
from pathlib import Path

from gitops.core import core_compose
from gitops.enginectl import ensure_network, network_is_internal, project_networks
from gitops.omsettings import write_runtime_files
from gitops.omstate import CORE_DIR, EDGE, EGRESS, ROUTER, STATE_DIR, run
from gitops.svclabels import service_labels

# Every service folder (compose project) gets its own internal network, so a compromised service cannot
# reach the services of another folder in the same workspace. om points the folder's workspace network
# at it with a compose override; the router and om_egress are attached to each (enginectl.connect_router).
# `om.network=shared` on a service keeps its folder on the workspace network; om.link joins two services.
WS_LABEL, PROJECT_LABEL = "om.workspace", "om.project"
SHARED_LABEL = "om.network"
OVERRIDE_DIR = STATE_DIR / "networks" / "overrides"

def project_network_name(ws: str, rel: str) -> str:
    """`<ws>_<folder>_net` from the folder's path in the workspace (`services/web` → `services-web`)."""
    return f"{ws}_{re.sub(r'[^a-z0-9]+', '-', rel.lower()).strip('-') or 'root'}_net"

def shares_workspace_network(cfg: dict | None) -> bool:
    return any(str(service_labels(svc).get(SHARED_LABEL, "")).strip().lower() == "shared"
               for svc in ((cfg or {}).get("services") or {}).values())

def workspace_network_keys(cfg: dict | None, ws: str) -> list[str]:
    """The project's compose network keys that name the workspace network."""
    return sorted(k for k, n in ((cfg or {}).get("networks") or {}).items() if (n or {}).get("name") == f"{ws}_net")

def service_project_network_key(cfg: dict | None, svc_name: str) -> str:
    """The project network key used by svc to connect to its project network."""
    nets = (cfg or {}).get("networks") or {}
    services = (cfg or {}).get("services") or {}
    svc = services.get(svc_name) or {}
    mapped = sorted(k for k, n in nets.items()
                    if (n or {}).get("name") or (k == "default" and not (n or {}).get("external")))
    svc_nets = svc.get("networks") or []
    if isinstance(svc_nets, dict):
        svc_nets = list(svc_nets.keys())
    for k in svc_nets:
        if k in mapped:
            return k
    if not svc_nets and "default" in mapped:
        return "default"
    return "om_project"

def project_network(runtime: str, ws: str, rel: str, project_dir: Path, cfg: dict | None) -> tuple[str | None, Path | None]:
    """(network, compose override) isolating this project, however its compose file is written:
      - the workspace network and the implicit `default` network become the project's own internal
        network `<ws>_<folder>_net` (the router and, if needed, om_egress are attached to it);
      - networks the file defines itself become internal and get a per-folder name (compose would name
        them after the workspace, so two folders defining `backend` would share it);
      - every service not on the project network yet joins it, so the edge can reach it.
    Another stack's external network is left alone here; the policy gate refuses it (`networks`).
    (None, None) with om.network=shared, without a readable config, or when nothing joins a network.
    Raises if the network cannot be made internal: the project is then not started."""
    path = OVERRIDE_DIR / f"{ws}-{hashlib.sha256(str(project_dir).encode()).hexdigest()[:12]}.yml"
    if cfg is None or shares_workspace_network(cfg):
        path.unlink(missing_ok=True)
        return None, None
    nets = cfg.get("networks") or {}
    services = cfg.get("services") or {}
    mapped = sorted(k for k, n in nets.items()
                    if (n or {}).get("name") == f"{ws}_net" or (k == "default" and not (n or {}).get("external")))
    own = sorted(k for k, n in nets.items() if k not in mapped and not (n or {}).get("external"))
    joins = [s for s, svc in sorted(services.items()) if not (svc or {}).get("network_mode")
             and not set((svc or {}).get("networks") or {}) & set(mapped)]
    if not (mapped or own or joins):
        path.unlink(missing_ok=True)
        return None, None
    net = project_network_name(ws, rel)
    if run([runtime, "network", "inspect", net]).returncode != 0:
        r = run([runtime, "network", "create", "--internal", "--label", f"{WS_LABEL}={ws}", "--label", f"{PROJECT_LABEL}={rel or '.'}", net])
        if r.returncode != 0:
            raise RuntimeError(f"cannot create {net}: {(r.stderr or r.stdout).strip()[-200:]}")
    if not network_is_internal(runtime, net) or net not in project_networks(runtime, ws):
        raise RuntimeError(f"{net} exists but is not an internal om project network (remove it: {runtime} network rm {net})")
    stem = net[:-len("_net")]
    lines = ["# Generated by om — this project's own internal network(s). Do not edit.", "networks:"]
    for k in mapped:
        lines += [f"  {json.dumps(k)}:", f"    name: {json.dumps(net)}", "    external: true"]
    for k in own:
        lines += [f"  {json.dumps(k)}:", f"    name: {json.dumps(stem + '_' + re.sub(r'[^a-z0-9]+', '-', k.lower()).strip('-'))}",
                  "    internal: true"]
    if joins:
        lines += ['  "om_project":', f"    name: {json.dumps(net)}", "    external: true", "services:"]
        for svc in joins:
            lines += [f"  {json.dumps(svc)}:", "    networks:", "      om_project: {}"]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return net, path

def prune_project_networks(runtime: str, ws: str, keep: set) -> list[str]:
    """Remove the workspace's project networks not in keep (their folder is gone). Returns removed names."""
    removed = []
    for net in project_networks(runtime, ws):
        if net in keep:
            continue
        for c in (ROUTER, EGRESS):
            run([runtime, "network", "disconnect", "-f", net, c])
        if run([runtime, "network", "rm", net]).returncode == 0:
            removed.append(net)
    return removed

def ensure_workspace_network(workspace_id: str, runtime: str = "podman") -> str:
    """Ensure the workspace's dedicated bridge network exists; new ones are internal (no way out
    except om_egress). An existing open network is reported, never changed: `om network harden`."""
    net_name = f"{workspace_id}_net"
    if not ensure_network(runtime, net_name, internal=True):
        print(f"\033[33mWarning: failed to create network {net_name}\033[0m")
    elif not network_is_internal(runtime, net_name):
        print(f"\033[33m⚠ {net_name} still has open internet access. Run `om network harden` "
              "(services then reach only the hosts in their om.egress label).\033[0m")
    return net_name

def _mounted_caddyfile_is_stale(runtime: str) -> bool:
    """A single-file bind mount pins the inode: editors that replace the file leave the
    container reading the old one, so a plain reload would silently apply stale config."""
    host = (CORE_DIR / "caddy" / "Caddyfile").read_text(encoding="utf-8")
    inside = run([runtime, "exec", EDGE, "cat", "/etc/caddy/Caddyfile"])
    return inside.returncode == 0 and inside.stdout != host

def reload_caddy(runtime: str = "podman", workspace_id: str | None = None, quiet: bool = False) -> bool:
    """Validate, then hot-reload the edge route table (recreating the edge if its Caddyfile mount is stale)."""
    state = run([runtime, "container", "inspect", "--format", "{{.State.Running}}", EDGE])
    if state.returncode != 0 or state.stdout.strip() != "true":
        if not quiet:
            print("\033[33mℹ Edge proxy is not running; routes apply on next `om core start`.\033[0m")
        return False

    if _mounted_caddyfile_is_stale(runtime):
        write_runtime_files(runtime)
        r = run(core_compose(runtime, "up", "-d", "--force-recreate", "caddy"), cwd=CORE_DIR)
        ok = r.returncode == 0
        if not quiet:
            print("\033[32m✓ Edge proxy recreated with the updated Caddyfile.\033[0m" if ok
                  else f"\033[31mEdge recreate failed:\033[0m {(r.stderr or r.stdout).strip()[-800:]}")
        return ok

    val = run([runtime, "exec", EDGE, "caddy", "validate", "--config", "/etc/caddy/Caddyfile"])
    if val.returncode != 0:
        lines = [ln for ln in (val.stderr or val.stdout).splitlines() if "error" in ln.lower()] or [(val.stderr or val.stdout).strip()]
        print(f"\033[31m✗ Caddy config invalid — live routes left unchanged:\033[0m {lines[-1][-600:]}")
        return False
    res = run([runtime, "exec", EDGE, "caddy", "reload", "--config", "/etc/caddy/Caddyfile"])
    if res.returncode == 0:
        if not quiet:
            print("\033[32m✓ Caddy route table hot-reloaded (zero downtime).\033[0m")
        return True
    print(f"\033[31mCaddy reload error: {res.stderr.strip()[-600:]}\033[0m")
    return False
